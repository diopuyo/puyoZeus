def board_text(board: list[list[int]]) -> str:
    """先頭の空行だけを省略して13×6盤面を可逆に表す。"""
    first = next((i for i, row in enumerate(board) if any(row)), len(board))
    return f'空{first}行;' + '/'.join(''.join(str(c) for c in row) for row in board[first:])


def board_table() -> tuple[str, list[str], list[list[Any]]]:
    """全STABLE変化盤面を落とさず一覧化する。"""
    values = json.loads((OUT / 'stable_boards.json').read_text())
    first = json.loads((OUT / 'first_proof_inputs.json').read_text())['latest'][0]
    values.insert(0, dict(t=first['t_sec'], side=1, board=first['board']))
    rows = []
    for value in values:
        cells = sum(value['board'], [])
        stamp, side = value['t'], value['side']
        note = '記録STABLE'
        if stamp < 1720:
            note = '区間前の最終STABLE、連鎖中の凍結元'
        if side == 1 and 1727 < stamp < 1730:
            note = '残像/部分更新、実盤面とはしない'
        if side == 1 and stamp >= 1735:
            note = '勝敗演出の誤認識' if stamp < 1738 else '次試合'
        if stamp >= 1738:
            note = '次試合'
        rows.append([f'{stamp:.3f}', f'{side}P', sum(1 <= c <= 5 for c in cells),
                     cells.count(9), board_text(value['board']), note])
    return ('7. 全STABLE変化盤面（認識原票）', ['秒', '側', '色数', '邪魔数', '盤面', '区別'], rows)


def markdown(title: str, columns: list[str], rows: list[list[Any]]) -> str:
    """指定の全表をMarkdownへ変換する。"""
    lines = [f'## {title}', '', '|'+ '|'.join(columns)+'|', '|'+ '|'.join(['---']*len(columns))+'|']
    lines += ['|'+'|'.join(str(v).replace('|', '/') for v in row)+'|' for row in rows]
    return '\n'.join(lines)


