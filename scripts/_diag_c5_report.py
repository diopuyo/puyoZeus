    text = '\n\n'.join(markdown(*table) for table in tables)+'\n'
    (OUT / 'ALL_TABLES.md').write_text(text, encoding='utf-8')
    sources = [BASE / 'collect/records/c5.jsonl.gz', BASE / 'v2c/short/c5/events.jsonl',
               BASE / 'v2c/short/c5/post_counter_bound_audit.json']
